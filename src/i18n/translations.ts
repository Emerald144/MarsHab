export type TranslationKey = keyof typeof myanmar;
export type Language = "en" | "my";
export type TranslationValues = Record<string, string | number>;
export const LANGUAGE_STORAGE_KEY = "terranexis-language";

/** Dynamic display data uses the same dictionary, with a safe English fallback. */
export function translate(language: Language, source: string, values?: TranslationValues): string {
  const template =
    language === "my" && Object.hasOwn(myanmar, source)
      ? myanmar[source as TranslationKey]
      : source;
  return template.replace(/\{(\w+)\}/g, (token, key: string) =>
    values && Object.hasOwn(values, key) ? String(values[key]) : token,
  );
}
